"""Original dummy invoices and bank statements for the submission; no personal data."""
import json
from pathlib import Path
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import landscape,A4
ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'samples'

def make(name,title,headers,rows,subtitle):
    w,h=landscape(A4);c=canvas.Canvas(str(OUT/(name+'.pdf')),pagesize=(w,h))
    c.setFillColorRGB(.1,.2,.15);c.setFont('Helvetica-Bold',23);c.drawString(32,h-55,title)
    c.setFont('Helvetica',9);c.setFillColorRGB(.4,.5,.35);c.drawString(32,h-80,subtitle)
    c.setFont('Helvetica',8);c.drawString(32,h-100,'DUMMY DATA ONLY / TABLEFLOW BENCHMARK / 2026')
    x=32;y=h-130;cw=(w-64)/len(headers);rh=30
    c.setFillColorRGB(.9,.95,.82);c.rect(x,y-rh,cw*len(headers),rh,stroke=0,fill=1)
    c.setStrokeColorRGB(.5,.6,.43);c.setLineWidth(.5)
    for i in range(len(rows)+2):c.line(x,y-i*rh,w-32,y-i*rh)
    for j in range(len(headers)+1):c.line(x+j*cw,y,x+j*cw,y-(len(rows)+1)*rh)
    for i,row in enumerate([headers]+rows):
        c.setFont('Helvetica-Bold' if i==0 else 'Helvetica',7)
        c.setFillColorRGB(.15,.25,.14)
        for j,v in enumerate(row):c.drawString(x+j*cw+4,y-i*rh-18,v)
    c.setFont('Helvetica',8);c.setFillColorRGB(.5,.58,.44);c.drawString(32,35,'Generated by Tableflow. All names, identifiers, transactions and amounts are fictitious.')
    c.save();(OUT/(name+'-ground-truth.json')).write_text(json.dumps({'headers':headers,'rows':rows},indent=2))

